def load_version(package_name: str) -> str:
    """ Assumes that each provided package has a __version__ variable provided in e.g. a _version.py file"""
    try:
        pac=importlib.import_module(package_name)
        return pac.__version__
    except Exception as ex:
        warn(f"{package_name}:could not import version information: {str(ex)}")
        return f"unknown"
def generate_remote(git_repo:str, package_name:str, version=None):
    """ Generates a remote path for a package hosted on GitHub.
    Args:
        git_repo (str): The GitHub repository URL.
        package_name (str): The name of the package.
        version (str, optional): The version of the package. Defaults to main branch.
    """
    if not version:
        ver= 'main'
    else:
        ver=get_version_hash(version, package_name=package_name)
    path=f"{git_repo}/{package_name.replace('.git','')}.git"
    path += f"@{ver}"
    return path

def dump_versions(versions):
    # DUMP
    version_file='package_versions.yaml'
    time=datetime.datetime.now().astimezone()
    versions.update({'__comment__': 
                    f'This file was auto-generated by {__file__}.'
                    f"( timestamp {time.isoformat()}({time.tzinfo}) )"
    })
    with open(version_file, 'w') as f:
        yaml.dump(versions, f)
    info(f"Wrote package versions to file {version_file}")
    return version_file

def make_versions(pacs:List[str]) -> dict:
    versions=dict()
    for pac in pacs:
        version=load_version(pac)
        versions[pac]=version
        debug(f"Package {pac} has version {version}")
    # dump versions to file
    return versions

def update_env(conda_env:dict, remotes:dict, name=None) -> dict:

    new_env=copy.deepcopy(conda_env.copy())
    if name:
        new_env['name']=name
    else:
        new_env['name']=make_test_name(new_env['name'])

    # The versions will go into dependencies
    if not 'dependencies' in new_env:
        new_env['dependencies']=list()
    deps=new_env['dependencies']

    # Check if pip dependencies are already there (should be dict of length 1 {pip: <list>}) else make empty list
    pip_dep=dict(pip=list())
    pos=-1
    for i,dep in enumerate(deps):
        if isinstance(dep, dict) and 'pip' in dep:
            pip_dep=dep
            pos=i
            break
    pips=pip_dep['pip']

    # Update the list
    # remotes.pop('qcpAPI', None)  # qcpAPI is installed through conda, not pip
    for pac,path in remotes.items():
        pattern=f"^git\\+ssh://git@github.com/bruno-von-bruening/{pac}.git"
        # Drop old entries
        for dep in pips:
            if re.match(pattern, dep):
                debug(f"Removing old dependency entry {dep}")
                pips.remove(dep)
        pips.append(path)
    pip_dep['pip']=pips
    new_env['dependencies'][pos]=pip_dep

    return new_env

_DIRTY_RE = re.compile(r'\+g?[0-9a-fA-F]+\.d\d+')   # version contains dirty tag

def _is_dirty(version_tag: str) -> bool:
    """Return True if the version string carries a dirty suffix (e.g. +g50eb2b584.d20260127)."""
    return bool(_DIRTY_RE.search(str(version_tag)))


@val_call
def export_clone_script(
    repo_name:str,
    commit:str,
    user:str='bruno-von-bruening',
    private:bool=False,
    output_file:str|None=None,
    envo_name:str|None=None,
) -> str:
    """Return a single git clone command string for *repo_name* pinned to *commit*.

    Args:
        repo_name: Repository / package name (without ``.git``).
        commit: Exact commit hash to check out after cloning.
        user: GitHub organisation or user owning the repository.
        private: If True use SSH, otherwise HTTPS.
    """
    if private:
        repo_url = f"git@github.com:{user}/{repo_name}.git"
    else:
        repo_url = f"https://github.com/{user}/{repo_name}.git"
    
    dir_name=f"{repo_name}_{commit}/"
    cmd= [f"git clone {repo_url} -n {dir_name}&& git -C {dir_name} checkout {commit}"]
    if envo_name:
        cmd[-1]+=f"&& \\ "
        cmd+=[f"cd {dir_name} && conda env create -f install/{repo_name}_env.yaml -n {envo_name}"]


    lines: list[str] = [
        '#!/usr/bin/env bash',
        '# Auto-generated clone script — do NOT edit by hand.',
        f'# Generated by {__file__} at {datetime.datetime.now().astimezone().isoformat()}',
        'set -euo pipefail',
        '',
    ]+cmd

    content='\n'.join(lines) + '\n'

    if output_file is None:
        output_file = f'clone_{repo_name}.sh'
    with open(output_file, 'w') as fh:
        fh.write(content)
    os.chmod(output_file, 0o755)
    # info(f"Clone script written to {output_file}")
    return output_file




@val_call
def drop_versions(packages:List[str]):

    # load packages through string
    versions=make_versions(packages)
    versions_file=dump_versions(versions)

    return versions_file

