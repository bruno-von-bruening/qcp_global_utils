def test_install():
    """ Test installation of conda environment file """

@val_call
def main(
    main_package:str, 
    dependencies:List[str], 
    conda_env_file: pdtc_file|None=None,
    test:bool=True,
    no_update:bool=False,
) -> None:
    
    update=not no_update

    if update:
        packages=[
            main_package,
            *dependencies
        ]
        versions_file=drop_versions(packages)

        # Load versions from file
        versions=load_json_or_yaml(versions_file)

        brunos_git='git+ssh://git@github.com/bruno-von-bruening'
        remotes=dict( (pac, generate_remote(brunos_git, pac, version=ver)) for pac,ver in versions.items() if not pac.startswith('_') and pac in dependencies )
    else:
        if not test:
            print(f"Neither update nor test requested, nothing to do!")

    # Write new conda environment file
    if conda_env_file:
        # Load conda environment file
        env_content=load_json_or_yaml(conda_env_file)
        if not no_update:
            # update old entries
            env_content=update_env(env_content, remotes)

            new_env_file='test_'+conda_env_file
            with open(new_env_file, 'w') as wr:
                yaml.dump(env_content, wr, sort_keys=False, indent=2) # same ordering as initial data
                info(f"Wrote new environment file: {new_env_file}")
        else:
            new_env_file=conda_env_file
    else:
        new_env_file=None

    if test:
        if not conda_env_file:
            raise Exception("Cannot test installation since no conda_env_file was provided to be updated!")
        info(f"Test requested: will try to update conda environment from file {new_env_file}...")
        try:
            conda_update_env(new_env_file)
        except Exception as ex:
            raise Exception(f"Could not update conda environment from file {new_env_file}: {ex}")

    return new_env_file


def main_parser(MAIN_PKG, DEPENDENCIES):

    import argparse as ap
    desc="Export the conda environment with the current package versions." \
    "If nothing provided then just print a yaml file informing about the current environment." \
    "If a conda environment file is provided, then update it with the current package versions." 
    epilog='\n'.join(["Example usage:"]+[ f"  - {x} : {y}" for x,y in [
        ('Print current environment info to file', 'qcp_export_envo.py'),
        ('Update existing conda environment file', 'qcp_export_envo.py -f <my_envo>.yaml'),
        ('Test updated conda environment', 'qcp_export_envo.py -f <my_envo>.yaml -t'),
    ] ] +[
        f"Finally activate this environment and check if it passes the tests."
    ])
    par=ap.ArgumentParser(description=desc, epilog=epilog, formatter_class=ap.RawDescriptionHelpFormatter)
    add=par.add_argument
    add( '--env-file', '-f', type=str, default=None,
        help="Path to the conda environment file. It will be update with current environment data (can be distable through --no-update)."
    )
    # give option to leave conda file alond and just test it
    add( '--no-update', '-n', action='store_true',
        help="If set, then do not update the conda environment file. but just test it"
    )
    add( '--test', '-t', action='store_true',
        help="If set, then do not write the updated environment to file, just print it."
    )
    args=par.parse_args()
    conda_env_file=args.env_file
    test=args.test

    main(MAIN_PKG, DEPENDENCIES, conda_env_file=conda_env_file, test=test, no_update=args.no_update)